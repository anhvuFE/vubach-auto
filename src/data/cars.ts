/** Static base date so createdAt is deterministic (no Date.now at import). */
const BASE_DATE = new Date('2025-06-01T00:00:00Z').getTime();
const DAY = 24 * 60 * 60 * 1000;

const buildCars = (seeds: CarSeed[]): Car[] =>
  seeds.map((seed, index) => {
    const id = `car-${String(index + 1).padStart(2, '0')}`;
    // Newer index = listed more recently, so featured/newest sort is sensible.
    const createdAt = new Date(BASE_DATE + index * DAY).toISOString();
    return {
      ...seed,
      id,
      slug: buildCarSlug({ brand: seed.brand, model: seed.model, year: seed.year, id }),
      createdAt,
      updatedAt: createdAt,
    };
  });

export const CARS: Car[] = buildCars(SEEDS);

/** Convenience selectors (pure, no side effects). */
export const getAvailableCars = (): Car[] => CARS.filter((c) => c.status !== 'sold');
export const getSoldCars = (): Car[] => CARS.filter((c) => c.status === 'sold');
export const getFeaturedCars = (limit = 6): Car[] =>
  CARS.filter((c) => c.isFeatured && c.status === 'available').slice(0, limit);
export const getCarBySlug = (slug: string): Car | undefined =>
  CARS.find((c) => c.slug === slug);
export const getSimilarCars = (car: Car, limit = 3): Car[] =>
  CARS.filter(
    (c) => c.id !== car.id && c.status === 'available' && c.bodyType === car.bodyType,
  ).slice(0, limit);

/** Seed export used by the admin store to reset/initialise inventory. */
export const CAR_INPUT_SEEDS: CarInput[] = SEEDS.map((seed) => ({ ...seed }));
